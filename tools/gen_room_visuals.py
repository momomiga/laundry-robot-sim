#!/usr/bin/env python3
"""Textured, visual-only OBJ overlays for the corridor (assets/room/vis_*.obj).

Each OBJ holds quads of ONE material (UV in world metres / tile size). They sit a few mm
proud of the plain-colour boxes in room.urdf, which stay the collision/fallback visuals.
Loaded by scripts/room_visuals.py. Standard library only.
"""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).parent))
import params as P

OUT = Path(__file__).resolve().parent.parent / "assets/room"
EPS = 0.002


class Obj:
    def __init__(self):
        self.v, self.vt, self.vn, self.f = [], [], [], []

    def quad(self, o, du, dv, su, sv, normal, tile=(0.5, 0.5), uv0=(0.0, 0.0)):
        """Rectangle o + a*du + b*dv, a in [0,su], b in [0,sv] (du, dv unit vectors).
        UV = (a/tile[0], b/tile[1]) + uv0. Winding is fixed to match `normal`."""
        c = [(0, 0), (su, 0), (su, sv), (0, sv)]
        pts = [tuple(o[i] + a * du[i] + b * dv[i] for i in range(3)) for a, b in c]
        uvs = [(a / tile[0] + uv0[0], b / tile[1] + uv0[1]) for a, b in c]
        cr = (du[1] * dv[2] - du[2] * dv[1], du[2] * dv[0] - du[0] * dv[2], du[0] * dv[1] - du[1] * dv[0])
        if sum(cr[i] * normal[i] for i in range(3)) < 0:
            pts, uvs = pts[::-1], uvs[::-1]
        base = len(self.v)
        self.v += pts
        self.vt += uvs
        self.vn.append(normal)
        self.f.append([(base + k + 1, base + k + 1, len(self.vn)) for k in range(4)])

    def write(self, path):
        s = ["# generated by tools/gen_room_visuals.py"]
        s += [f"v {x:.5f} {y:.5f} {z:.5f}" for x, y, z in self.v]
        s += [f"vt {u:.5f} {v:.5f}" for u, v in self.vt]
        s += [f"vn {x:.3f} {y:.3f} {z:.3f}" for x, y, z in self.vn]
        s += ["f " + " ".join(f"{a}/{b}/{c}" for a, b, c in q) for q in self.f]
        Path(path).write_text("\n".join(s) + "\n")


X, Y, Z = (1, 0, 0), (0, 1, 0), (0, 0, 1)


def build_all():
    drop = P.GENKAN_DROP
    t = P.WALL_T
    W = P.ROOM_W
    y0, y1 = P.UPPER_Y
    yg = P.GENKAN_Y[0]
    xc0, xc1 = P.CORRIDOR_X
    xr = P.RIGHT_COL_X[0]
    H = P.WALL_H
    m = {k: Obj() for k in ("wood", "wallpaper", "tile", "door_light", "door_dark", "glass_frosted", "glass_slit")}

    # ---- floors ----  (wood planks run along world y: u = y, v = x)
    m["wood"].quad((0, y0, EPS), Y, X, yg - y0, xc1, (0, 0, 1), tile=(0.6, 0.6))
    m["tile"].quad((0, yg, -drop + EPS), X, Y, xc1, P.GENKAN_Y[1] - yg, (0, 0, 1), tile=(0.6, 0.6))
    m["wood"].quad((0, yg, -drop), X, Z, xc1, drop, (0, 1, 0), tile=(0.6, 0.6))   # step riser

    # ---- walls (wallpaper) ----
    def wall(o, du, su, normal, z0, z1):
        m["wallpaper"].quad((o[0], o[1], z0), du, Z, su, z1 - z0, normal, tile=(0.7, 0.7), uv0=(o[0] + o[1], z0))

    wall((EPS, y0, 0), Y, yg - y0, (1, 0, 0), 0, H)                 # x=0 wall
    wall((EPS, yg, 0), Y, P.GENKAN_Y[1] - yg, (1, 0, 0), -drop, H)
    wall((xr - EPS, y0, 0), Y, yg - y0, (-1, 0, 0), 0, H)           # corridor-side wall of the right column
    wall((xr - EPS, yg, 0), Y, P.GENKAN_Y[1] - yg, (-1, 0, 0), -drop, H)
    wall((0, P.GENKAN_Y[1] - EPS, 0), X, xr, (0, -1, 0), -drop, H)  # entrance wall
    wall((0, y0 + EPS, 0), X, xc0, (0, 1, 0), 0, H)                 # partition, left of opening
    wall((xc1, y0 + EPS, 0), X, xr - xc1, (0, 1, 0), 0, H)          # partition, right of opening
    m["wallpaper"].quad((0, y0, H - EPS), X, Y, xr, P.GENKAN_Y[1] - y0, (0, 0, -1), tile=(0.7, 0.7))  # ceiling

    # ---- main-room door, open 90 deg into the main room, hinge at x = DOOR_X[0] ----
    xd0 = P.DOOR_X[0]
    yh, yf = P.PARTITION_Y[0], P.PARTITION_Y[0] - P.ROOM_DOOR_W
    th, dh = P.ROOM_DOOR_T, P.ROOM_DOOR_H
    for xf, n in ((xd0 - EPS / 2, (-1, 0, 0)), (xd0 + th + EPS / 2, (1, 0, 0))):
        m["door_light"].quad((xf, yf, 0), Y, Z, P.ROOM_DOOR_W, dh, n, tile=(0.8, 2.0))
        # slit window in the upper part (leaf: y from yf to yh)
        ys = yf + 0.2
        m["glass_slit"].quad((xf + n[0] * EPS, ys, 1.55), Y, Z, 0.4, 0.07, n, tile=(0.4, 0.07))
    m["door_light"].quad((xd0, yf - EPS, 0), X, Z, th, dh, (0, -1, 0), tile=(0.8, 2.0))   # free edge
    m["door_light"].quad((xd0, yh + EPS, 0), X, Z, th, dh, (0, 1, 0), tile=(0.8, 2.0))
    m["door_light"].quad((xd0, yf, dh + EPS), X, Y, th, P.ROOM_DOOR_W, (0, 0, 1), tile=(0.8, 2.0))

    # ---- toilet door (dark wood slab on the corridor wall) ----
    a, b = P.TOILET_DOOR_Y
    xs = xr - EPS * 4
    m["door_dark"].quad((xs, a, 0), Y, Z, b - a, P.DOOR_H, (-1, 0, 0), tile=(0.7, 2.0))

    # ---- bath folding door: frosted panels (frame/lattice are URDF boxes) ----
    a, b = P.BATH_DOOR_Y
    m["glass_frosted"].quad((xr - 0.015, a + 0.04, 0.06), Y, Z, b - a - 0.08, P.DOOR_H - 0.12, (-1, 0, 0), tile=(0.5, 0.5))

    for k, o in m.items():
        o.write(OUT / f"vis_{k}.obj")
    return list(m)


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    print(build_all())
