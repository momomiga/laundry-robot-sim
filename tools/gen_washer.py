#!/usr/bin/env python3
"""Generate assets/washer/washer.urdf (local frame: origin = opening centre on
the floor, front/operation side = +x). Place at P.WASHER_POS in the room frame."""
from pathlib import Path
import math
import sys

sys.path.insert(0, str(Path(__file__).parent))
import params as P
from urdf_util import *

OUT = Path(__file__).resolve().parent.parent / "assets/washer/washer.urdf"


def ring_shape(z, r_in, r_out, t, color, n=36) -> str:
    """Visual-only flat annulus at height z (centre of the slab): n radial boxes. Each box is as wide as the
    outer polygon edge, so neighbours overlap near r_in but never reach inside r_in (open hole radius >= r_in)."""
    w = 2 * r_out * math.tan(math.pi / n)
    s = ""
    for k in range(n):
        a = 2 * math.pi * k / n
        rm = (r_in + r_out) / 2
        s += box_shape((rm * math.cos(a), rm * math.sin(a), z), (r_out - r_in, w, t), rpy=(0, 0, a),
                       color=color, collision=False)
    return s


def build() -> str:
    D = P.WASHER_D                          # width across (y)
    H = P.WASHER_H
    xf = P.WASHER_OPEN_FRONT                # front face (x), origin = opening centre
    xb = xf - P.WASHER_W                    # back face (x)
    W = P.WASHER_W
    xc = (xf + xb) / 2                      # body centre (x)
    od = P.WASHER_OPEN_D
    side = P.WASHER_TUB_SIDE
    tub_z0 = H - P.WASHER_TUB_DEPTH       # tub bottom (top face of floor slab)
    wall_t = 0.02
    top_t = 0.03
    mats = (material("body", (0.92, 0.93, 0.95, 1)) + material("panel", (0.25, 0.3, 0.4, 1))
            + material("tub", (0.65, 0.68, 0.72, 1)) + material("lid", (0.8, 0.85, 0.9, 0.9)))
    b = inertial(P.WASHER_MASS, box_inertia(P.WASHER_MASS, W, D, H), (xc, 0, H / 2))
    # solid lower block (below the tub)
    b += box_shape((xc, 0, tub_z0 / 2), (W, D, tub_z0), color="body")
    # outer shell walls above the lower block (visual + collision)
    hh = H - tub_z0
    zc = tub_z0 + hh / 2
    b += box_shape((xf - wall_t / 2, 0, zc), (wall_t, D, hh), color="body")
    b += box_shape((xb + wall_t / 2, 0, zc), (wall_t, D, hh), color="body")
    b += box_shape((xc, D / 2 - wall_t / 2, zc), (W - 2 * wall_t, wall_t, hh), color="body")
    b += box_shape((xc, -D / 2 + wall_t / 2, zc), (W - 2 * wall_t, wall_t, hh), color="body")
    # tub: square prism of inner side `side` (anything that fits a diameter-side circle passes)
    ti = side / 2
    tw = 0.02
    b += box_shape((ti + tw / 2, 0, zc), (tw, side + 2 * tw, hh), color="tub")
    b += box_shape((-ti - tw / 2, 0, zc), (tw, side + 2 * tw, hh), color="tub")
    b += box_shape((0, ti + tw / 2, zc), (side, tw, hh), color="tub")
    b += box_shape((0, -ti - tw / 2, zc), (side, tw, hh), color="tub")
    # fill between tub and shell (solid slab right below the top plate) so nothing drops into the gap
    zt = H - top_t / 2
    ef, eb = xf - ti, -ti - xb               # front / back fill depth (x)
    b += box_shape(((xf + ti) / 2, 0, zt), (ef, D, top_t), color="body")
    b += box_shape(((xb - ti) / 2, 0, zt), (eb, D, top_t), color="body")
    ey = (D - side) / 2
    b += box_shape((0, (side + ey) / 2, zt), (side, ey, top_t), color="body")
    b += box_shape((0, -(side + ey) / 2, zt), (side, ey, top_t), color="body")
    # visual-only round opening: an annulus (polygon of thin boxes; URDF has no ring primitive) that covers the
    # corners of the square collision hole; its inner radius is the square's half side so the visible opening is
    # the inscribed circle (Ø side, ~ the measured Ø od); a thin rim marks the opening edge
    b += ring_shape(H + 0.0005, ti, math.hypot(ti, ti) + 0.003, 0.001, "body")
    b += ring_shape(H + 0.0015, ti, od / 2 + 0.01, 0.001, "tub")
    # control panel (visual) on the front top edge
    b += box_shape((xf - 0.03, 0, H - 0.07), (0.005, 0.40, 0.08), color="panel", collision=False)
    # a visual-only circular dark floor of the tub
    b += cyl_shape((0, 0, tub_z0 + 0.0005), ti, 0.001, color="panel", collision=False)
    # tub floor collision
    b += box_shape((0, 0, tub_z0 + 0.0), (side, side, 0.01), visual=False)

    out = mats + link("washer_body", b)
    # open lid: hinged at the hinge line behind the opening, standing up, tilted back 10 degrees past vertical
    lid_t = 0.02
    ll, lw = P.WASHER_LID
    lb = inertial(1.0, box_inertia(1.0, ll, lw, lid_t), (ll / 2, 0, lid_t / 2))
    lb += box_shape((ll / 2, 0, lid_t / 2), (ll, lw, lid_t), color="lid")
    out += link("lid", lb)
    out += joint("lid_hinge", "fixed", "washer_body", "lid", xyz=(xf - P.WASHER_HINGE_FRONT, 0, H),
                 rpy=(0, -math.radians(100), 0))
    return robot("washer", out, "generated by tools/gen_washer.py; vertical washer, front=+x, lid open and fixed")


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build())
    print("wrote", OUT)
