#!/usr/bin/env python3
"""Generate assets/robot/house_robot.urdf.

Robot frame: +x forward, +y left, z up, origin on the floor under the base centre.
Chain: world_anchor -(prismatic x)- base_x -(prismatic y)- base_y -(revolute z)- base_link
       base_link -(prismatic z lift)- carriage -(fixed)- PiPER (joint1..6, joint7/8 gripper).
PiPER links/joints are taken from assets/robot/piper/piper_description.urdf (upstream, unmodified
apart from relative mesh paths) so the arm stays identical to the official model.
"""
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, str(Path(__file__).parent))
import params as P
from urdf_util import *

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets/robot/house_robot.urdf"
PIPER = ROOT / "assets/robot/piper/piper_description.urdf"


def tiny_link(name, mass=0.1):
    return link(name, inertial(mass, (1e-3, 1e-3, 1e-3)))


def build() -> str:
    bx, by = P.BASE_SIZE
    z0, z1 = P.BASE_Z0, P.BASE_Z1
    mats = (material("chassis", (0.25, 0.28, 0.35, 1)) + material("wheel", (0.08, 0.08, 0.08, 1))
            + material("column", (0.6, 0.62, 0.65, 1)) + material("carriage", (0.9, 0.5, 0.1, 1))
            + material("basket", (0.2, 0.55, 0.8, 1)))
    out = mats
    # virtual holonomic base
    out += tiny_link("world_anchor") + tiny_link("base_x") + tiny_link("base_y")
    out += joint("base_x_joint", "prismatic", "world_anchor", "base_x", axis=(1, 0, 0),
                 limit=(-20, 20, 500, 2), damping=0.0)
    out += joint("base_y_joint", "prismatic", "base_x", "base_y", axis=(0, 1, 0),
                 limit=(-20, 20, 500, 2), damping=0.0)
    out += joint("base_yaw_joint", "revolute", "base_y", "base_link", axis=(0, 0, 1),
                 limit=(-6.2832, 6.2832, 200, 3), damping=0.0)

    # chassis, column, basket in a single base_link
    m_col, m_bsk = 1.5, 1.0
    mass = P.BASE_MASS
    b = inertial(mass, box_inertia(mass, bx, by, z1 - z0), (0, 0, (z0 + z1) / 2))
    b += box_shape((0, 0, (z0 + z1) / 2), (bx, by, z1 - z0), color="chassis")
    for sx in (1, -1):
        for sy in (1, -1):  # mecanum wheels, visual only
            b += cyl_shape((sx * 0.14, sy * (by / 2 - P.WHEEL_W / 2), P.WHEEL_R), P.WHEEL_R, P.WHEEL_W,
                           rpy=(1.5708, 0, 0), color="wheel", collision=False)
    cx, cy = P.COLUMN_XY
    b += box_shape((cx, cy, z1 + P.COLUMN_H / 2), (P.COLUMN_SIZE, P.COLUMN_SIZE, P.COLUMN_H), color="column")
    # basket: open-top box fixed on the platform
    ix, iy, iz = P.BASKET_INNER
    w = P.BASKET_WALL
    kx, ky = P.BASKET_CENTER_XY
    bz = z1
    b += box_shape((kx, ky, bz + w / 2), (ix + 2 * w, iy + 2 * w, w), color="basket")
    b += box_shape((kx + ix / 2 + w / 2, ky, bz + iz / 2), (w, iy + 2 * w, iz), color="basket")
    b += box_shape((kx - ix / 2 - w / 2, ky, bz + iz / 2), (w, iy + 2 * w, iz), color="basket")
    b += box_shape((kx, ky + iy / 2 + w / 2, bz + iz / 2), (ix, w, iz), color="basket")
    b += box_shape((kx, ky - iy / 2 - w / 2, bz + iz / 2), (ix, w, iz), color="basket")
    out += link("base_link", b)

    # lift carriage
    ax, ay = P.CARRIAGE_XY
    t = P.CARRIAGE_THK
    cw = 0.10
    plate_x0 = cx + P.COLUMN_SIZE / 2
    plate_x1 = ax + cw / 2
    cb = inertial(1.0, box_inertia(1.0, plate_x1 - plate_x0, cw, t), ((plate_x0 + plate_x1) / 2 - ax, 0, t / 2))
    cb += box_shape(((plate_x0 + plate_x1) / 2 - ax, 0, t / 2), (plate_x1 - plate_x0, cw, t), color="carriage")
    out += link("carriage", cb)
    out += joint("lift_joint", "prismatic", "base_link", "carriage", xyz=(ax, ay, z1 + 0.03),
                 axis=(0, 0, 1), limit=(P.LIFT_RANGE[0], P.LIFT_RANGE[1], 500, 0.2), damping=10.0)

    # PiPER arm (copied from upstream URDF; its root `base_link` is renamed to avoid a clash)
    root = ET.parse(PIPER).getroot()
    piper = ""
    for el in root:
        if el.tag == "link" and el.get("name") == "dummy_link":
            continue
        if el.tag == "joint" and el.get("name") == "base_to_dummy":
            continue
        if el.tag == "link" and el.get("name") == "base_link":
            el.set("name", "piper_base_link")
        for ref in el.findall("parent") + el.findall("child"):
            if ref.get("link") == "base_link":
                ref.set("link", "piper_base_link")
        for m in el.iter("mesh"):
            m.set("filename", "piper/" + m.get("filename"))
        ET.indent(el, space="  ", level=1)
        piper += "  " + ET.tostring(el, encoding="unicode").strip() + "\n"
    out += joint("carriage_to_piper", "fixed", "carriage", "piper_base_link", xyz=(0, 0, t))
    out += piper
    return robot("house_robot", out,
                 "generated by tools/gen_robot.py; PiPER part from agilexrobotics/piper_ros (MIT), see assets/robot/README.md")


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build())
    print("wrote", OUT)
